"""Generate engine/src/unicode_data.rs from Python's unicodedata.

Usage: python ref/gen_unicode.py
Tables: \\p{L} ranges (pre-tokenizer regex) and the NFC data (canonical
decompositions, combining classes, primary composites). Hangul is algorithmic
and not included.
"""

import sys
import unicodedata as ud
from pathlib import Path

OUT = Path(__file__).parent.parent / "engine/src/unicode_data.rs"
HANGUL = range(0xAC00, 0xAC00 + 11172)


def ranges(pred):
    """Inclusive (start, end, value) ranges of code points where pred is truthy."""
    out, start, prev = [], None, None
    for cp in range(sys.maxunicode + 2):
        v = pred(chr(cp)) if cp <= sys.maxunicode else None
        if v != prev:
            if prev:
                out.append((start, cp - 1, prev))
            start, prev = cp, v
    return out


def table(name, ty, rows):
    body = "".join(f"    ({', '.join(f'0x{x:X}' for x in row)}),\n" for row in rows)
    return f"pub const {name}: &[{ty}] = &[\n{body}];\n"


letters = [(a, b) for a, b, _ in ranges(lambda c: ud.category(c).startswith("L"))]
ccc = ranges(ud.combining)

decomp, compose = [], []
for cp in range(sys.maxunicode + 1):
    d = ud.decomposition(chr(cp))
    if not d or d.startswith("<") or cp in HANGUL:
        continue
    parts = [int(x, 16) for x in d.split()]
    decomp.append((cp, parts[0], parts[1] if len(parts) == 2 else 0))
    # Primary composite: a pair that NFC actually recomposes (not excluded).
    if len(parts) == 2 and ud.normalize("NFC", chr(parts[0]) + chr(parts[1])) == chr(cp):
        compose.append((parts[0], parts[1], cp))

OUT.write_text(
    f"// Generated by ref/gen_unicode.py from Unicode {ud.unidata_version}. Do not edit.\n"
    "\n"
    "/// Inclusive ranges of General_Category=L* code points.\n"
    + table("LETTER", "(u32, u32)", letters)
    + "\n/// Inclusive ranges with a non-zero Canonical_Combining_Class: (start, end, class).\n"
    + table("COMBINING_CLASS", "(u32, u32, u8)", ccc)
    + "\n/// Canonical decompositions, sorted by code point: (char, first, second or 0).\n"
    + table("DECOMPOSITION", "(u32, u32, u32)", decomp)
    + "\n/// Primary composites, sorted by pair: (first, second, composed).\n"
    + table("COMPOSITION", "(u32, u32, u32)", sorted(compose))
)
print(f"{len(letters)} letter ranges, {len(ccc)} ccc ranges, {len(decomp)} decompositions, {len(compose)} compositions")
